def fit_blend_weights(
    oof: pd.DataFrame,
    y,
    metric: Callable[[object, object], float],
    greater_is_better: bool = True,
    n_rounds: int = 50,
) -> pd.Series:
    """Веса взвешенного усреднения: жадный отбор моделей с возвращением (R. Caruana и др., 2004).

    - metric(y, предсказание) -> число; greater_is_better говорит, что лучше — больше или меньше;
    - алгоритм: набор моделей сначала пуст. На каждом из n_rounds шагов в набор добавляется та модель
      (любая, в том числе уже добавленная), с которой метрика простого среднего по набору наилучшая;
      при равенстве — первая по порядку столбцов. Добавление происходит на каждом шаге, даже если метрика
      при этом ухудшается;
    - из n_rounds получившихся наборов выбирается набор с наилучшей метрикой (при равенстве — самый
      короткий). Вес модели — число её вхождений в этот набор, делённое на размер набора;
    - следствия: веса неотрицательны и дают в сумме 1; метрика взвешенного среднего на oof не хуже
      метрики лучшей одиночной модели; при n_rounds=1 весь вес получает лучшая одиночная модель;
    - n_rounds < 1 — ValueError;
    - результат — Series float64 с именем "weight", индекс — названия моделей в порядке столбцов oof.
      oof и y не изменяются.

    Веса подбираются только на out-of-fold предсказаниях: на предсказаниях для объектов, на которых
    модели обучались, весь вес достанется самой переобученной модели.
    """
